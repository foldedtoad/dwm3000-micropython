"""
examples/ex_07a_ack_data_tx/main.py

MicroPython port of upstream ex_07a_ack_data_tx (ack_data_tx.c).

Sends a data frame that requests an acknowledgement (ACK request bit set in
the frame control) and waits for the receiver's automatic ACK. If no ACK
arrives the frame is retransmitted after TX_DELAY_MS/5; after an ACK the next
frame (sequence number + 1) goes out after TX_DELAY_MS. Run ex_07b_ack_data_rx
(or ex_07c) on the other board, receiver first.

The ACK is generated by the receiving chip itself (auto-ACK), so nothing here
is timing-critical for the host.
"""

import utime as time

from platform.port import port
from decadriver import deca_device as dwt
from decadriver import deca_regs as R
from decadriver.deca_types import DwtConfig
from config_options import txconfig_options

APP_NAME = "ACK DATA TX (MicroPython) v0.1"

config = DwtConfig(
    chan=5,
    txPreambLength=R.DWT_PLEN_128,
    rxPAC=R.DWT_PAC8,
    txCode=9,
    rxCode=9,
    sfdType=1,
    dataRate=R.DWT_BR_6M8,
    phrMode=R.DWT_PHRMODE_STD,
    phrRate=R.DWT_PHRRATE_STD,
    sfdTO=(129 + 8 - 8),
    stsMode=R.DWT_STS_MODE_OFF,
    stsLength=R.DWT_STS_LEN_64,
    pdoaMode=R.DWT_PDOA_M0,
)

# Data frame with ACK request (0x61 0x88): seq#, PAN 0xDECA, dest 'XR' (0x5258
# little endian = short address "RX"), source 'XT', then a payload.
tx_msg = bytearray([0x61, 0x88, 0, 0xCA, 0xDE, ord('X'), ord('R'), ord('X'), ord('T'),
                    ord('m'), ord('a'), ord('c'), ord('p'), ord('a'), ord('y'),
                    ord('l'), ord('o'), ord('a'), ord('d')])
FRAME_FC_IDX = 0
FRAME_SN_IDX = 2

# Expected ACK: frame control 0x02 0x00, same sequence number (5 bytes with FCS).
ACK_FC_0 = 0x02
ACK_FC_1 = 0x00
ACK_FRAME_LEN = 5

TX_DELAY_MS = 1000
# Receive timeout for the ACK, in uus (upstream 2200).
RX_RESP_TO_UUS = 2200


def main():
    print(APP_NAME)
    port.spi_set_rate_high()
    port.reset_dwic()
    time.sleep_ms(2)
    while not dwt.dwt_checkidlerc():
        pass
    if dwt.dwt_initialise(R.DWT_DW_IDLE) == R.DWT_ERROR:
        print("INIT FAILED")
        while True:
            pass
    if dwt.dwt_configure(config):
        print("CONFIG FAILED")
        while True:
            pass
    dwt.dwt_configuretxrf(txconfig_options)

    # Receiver on right after the frame is sent; give up if no ACK in time.
    dwt.dwt_setrxaftertxdelay(50)
    dwt.dwt_setrxtimeout(RX_RESP_TO_UUS)
    dwt.dwt_setlnapamode(R.DWT_LNA_ENABLE | R.DWT_PA_ENABLE)
    dwt.dwt_setleds(R.DWT_LEDS_ENABLE | R.DWT_LEDS_INIT_BLINK)

    tx_frame_len = len(tx_msg) + R.FCS_LEN
    tx_frame_nb = tx_frame_ack_nb = tx_frame_retry_nb = 0
    try:
        while True:
            tx_frame_acked = False
            dwt.dwt_writetxdata(tx_frame_len - R.FCS_LEN, bytes(tx_msg), 0)
            dwt.dwt_writetxfctrl(tx_frame_len, 0, 0)
            dwt.dwt_starttx(R.DWT_START_TX_IMMEDIATE | R.DWT_RESPONSE_EXPECTED)

            while True:
                status_reg = dwt.dwt_read32bitreg(R.SYS_STATUS_ID)
                if status_reg & (R.SYS_STATUS_RXFCG_BIT_MASK | R.SYS_STATUS_ALL_RX_TO | R.SYS_STATUS_ALL_RX_ERR):
                    break

            if status_reg & R.SYS_STATUS_RXFCG_BIT_MASK:
                dwt.dwt_write32bitreg(R.SYS_STATUS_ID, R.SYS_STATUS_RXFCG_BIT_MASK)
                frame_len = dwt.dwt_read32bitreg(R.RX_FINFO_ID) & R.RX_FINFO_RXFLEN_BIT_MASK
                if frame_len == ACK_FRAME_LEN:
                    rx_buffer = dwt.dwt_readrxdata(frame_len, 0)
                    if (rx_buffer[FRAME_FC_IDX] == ACK_FC_0 and rx_buffer[FRAME_FC_IDX + 1] == ACK_FC_1
                            and rx_buffer[FRAME_SN_IDX] == tx_msg[FRAME_SN_IDX]):
                        tx_frame_acked = True
                        tx_frame_ack_nb += 1
                        tx_frame_nb += 1
                        print("frame %d ACKed (%d sent, %d acked, %d retries)" %
                              (tx_msg[FRAME_SN_IDX], tx_frame_nb, tx_frame_ack_nb, tx_frame_retry_nb))
                        time.sleep_ms(TX_DELAY_MS)
                        tx_msg[FRAME_SN_IDX] = (tx_msg[FRAME_SN_IDX] + 1) & 0xFF
            else:
                dwt.dwt_write32bitreg(R.SYS_STATUS_ID, R.SYS_STATUS_ALL_RX_TO | R.SYS_STATUS_ALL_RX_ERR)

            if not tx_frame_acked:
                tx_frame_nb += 1
                print("frame %d: no ACK, retrying (%d sent, %d acked, %d retries)" %
                      (tx_msg[FRAME_SN_IDX], tx_frame_nb, tx_frame_ack_nb, tx_frame_retry_nb + 1))
                time.sleep_ms(TX_DELAY_MS // 5)
                tx_frame_retry_nb += 1
    except KeyboardInterrupt:
        dwt.dwt_forcetrxoff()
        print("\nStopped by user (Ctrl-C). Transceiver forced off.")


if __name__ == "__main__":
    main()
